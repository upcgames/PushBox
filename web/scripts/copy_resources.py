import json
import re
import shutil
from pathlib import Path

WEB_DIR = Path(__file__).resolve().parent.parent
SOURCE_DIR = WEB_DIR.parent / 'Retro Push Box'
TARGET_DIR = WEB_DIR / 'public' / 'audio'
MANIFEST = WEB_DIR / 'src' / 'generated' / 'audioAssets.js'


def audio_manifest(source, filenames):
    """Validate exact resource names, even on a case-insensitive filesystem."""
    filenames = sorted(filenames)
    folded = {}
    for filename in filenames:
        previous = folded.setdefault(filename.casefold(), filename)
        if previous != filename:
            raise ValueError(f'Ambiguous audio filenames: {previous}, {filename}')
    requested = set(re.findall(r'PlaySound\s*\(\s*TEXT\s*\(\s*"([^"]+\.wav)"\s*\)', source))
    for filename in sorted(requested):
        if filename not in filenames:
            actual = folded.get(filename.casefold())
            detail = f' (asset spelling: {actual})' if actual else ''
            raise ValueError(f'Canonical audio asset missing: {filename}{detail}')
    ending = re.search(r'void\s+MusicaCongratulations\s*\(\s*\)\s*\{\s*PlaySound\s*\(\s*TEXT\s*\(\s*"([^"]+)"', source)
    if not ending:
        raise ValueError('Canonical MusicaCongratulations audio reference not found')
    return filenames, ending.group(1)


def copy_resources():
    source = (SOURCE_DIR / 'Source Code.cpp').read_text()
    assets = [path for path in SOURCE_DIR.iterdir() if path.suffix.lower() == '.wav']
    filenames, ending = audio_manifest(source, [path.name for path in assets])
    # Validate before touching outputs. Remove stale generated names first so
    # case-only renames also take effect on case-insensitive filesystems.
    TARGET_DIR.mkdir(parents=True, exist_ok=True)
    for path in TARGET_DIR.iterdir():
        if path.suffix.lower() == '.wav' and path.name not in filenames:
            path.unlink()
    for asset in assets:
        shutil.copy2(asset, TARGET_DIR / asset.name)
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text('// Generated by scripts/copy_resources.py; do not edit.\n'
                        f'export const AUDIO_FILES = Object.freeze({json.dumps(filenames, indent=2)});\n'
                        f'export const CONGRATULATIONS_MUSIC = {json.dumps(ending)};\n')
    print(f'Validated and copied {len(assets)} audio assets; generated the shared audio manifest.')


if __name__ == '__main__':
    copy_resources()
