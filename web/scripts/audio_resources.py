import json
import re
from pathlib import Path

WEB_DIR = Path(__file__).resolve().parent.parent
SOURCE_DIR = WEB_DIR.parent / 'Retro Push Box'
TARGET_DIR = WEB_DIR / 'public' / 'audio'
MANIFEST = WEB_DIR / 'src' / 'generated' / 'audioAssets.js'


def web_audio_source(source):
    """Emit direct MP3 requests for web code while leaving C++ untouched."""
    return re.sub(r'(PlaySound\s*\(\s*TEXT\s*\(\s*"[^"\n]+)\.wav("\s*\))',
                  r'\1.mp3\2', source)


def audio_manifest(source, filenames):
    """Validate the committed MP3 assets against web sound requests."""
    source = web_audio_source(source)
    filenames = sorted(filenames)
    folded = {}
    for filename in filenames:
        previous = folded.setdefault(filename.casefold(), filename)
        if previous != filename:
            raise ValueError(f'Ambiguous audio filenames: {previous}, {filename}')
    requested = set(re.findall(r'PlaySound\s*\(\s*TEXT\s*\(\s*"([^"]+\.mp3)"\s*\)', source))
    for filename in sorted(requested):
        if filename not in filenames:
            actual = folded.get(filename.casefold())
            detail = f' (asset spelling: {actual})' if actual else ''
            raise ValueError(f'Web audio asset missing: {filename}{detail}')
    ending = re.search(r'void\s+MusicaCongratulations\s*\(\s*\)\s*\{\s*PlaySound\s*\(\s*TEXT\s*\(\s*"([^"]+)"', source)
    if not ending:
        raise ValueError('Canonical MusicaCongratulations audio reference not found')
    return filenames, ending.group(1)


def generate_audio_manifest():
    source = (SOURCE_DIR / 'Source Code.cpp').read_text()
    filenames, ending = audio_manifest(source, [path.name for path in TARGET_DIR.glob('*.mp3')])
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text('// Generated by scripts/audio_resources.py; do not edit.\n'
                        f'export const AUDIO_FILES = Object.freeze({json.dumps(filenames, indent=2)});\n'
                        f'export const CONGRATULATIONS_MUSIC = {json.dumps(ending)};\n')
    print(f'Validated {len(filenames)} MP3 assets; generated the shared audio manifest.')


if __name__ == '__main__':
    generate_audio_manifest()
